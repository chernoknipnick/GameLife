import { describe, expect, it } from 'vitest';
import { dayBefore, dayKey, nextDay, pluralDays, weekdayIndex } from './day.js';

describe('ключ суток', () => {
  it('час ночи при смене суток в 4 утра относится ко вчера', () => {
    // Раздел 6.1: сутки меняются в dayResetHour, а не в полночь.
    expect(dayKey(new Date(2026, 7, 27, 1, 30), 4)).toBe('2026-08-26');
  });

  it('четыре утра — уже новые сутки', () => {
    expect(dayKey(new Date(2026, 7, 27, 4, 0), 4)).toBe('2026-08-27');
  });

  it('полночь без сдвига даёт календарный день', () => {
    expect(dayKey(new Date(2026, 7, 27, 0, 10), 0)).toBe('2026-08-27');
  });
});

describe('сдвиг суток', () => {
  it('переходит через начало месяца', () => {
    expect(dayBefore('2026-09-01')).toBe('2026-08-31');
    expect(nextDay('2026-08-31')).toBe('2026-09-01');
  });

  it('переходит через новый год', () => {
    expect(dayBefore('2027-01-01')).toBe('2026-12-31');
    expect(nextDay('2026-12-31')).toBe('2027-01-01');
  });

  it('знает про високосный февраль', () => {
    expect(nextDay('2028-02-28')).toBe('2028-02-29');
    expect(dayBefore('2028-03-01')).toBe('2028-02-29');
  });

  it('сдвиг туда и обратно возвращает исходный ключ', () => {
    expect(dayBefore(nextDay('2026-08-27'))).toBe('2026-08-27');
  });
});

describe('склонение дней', () => {
  it.each([
    [1, '1 день'],
    [2, '2 дня'],
    [4, '4 дня'],
    [5, '5 дней'],
    [11, '11 дней'],
    [14, '14 дней'],
    [21, '21 день'],
    [22, '22 дня'],
    [25, '25 дней'],
    [111, '111 дней'],
    [121, '121 день'],
  ])('%i → %s', (count, expected) => {
    expect(pluralDays(count)).toBe(expected);
  });
});

describe('день недели', () => {
  it('27 августа 2026 — четверг', () => {
    expect(weekdayIndex('2026-08-27')).toBe(4);
  });
});
